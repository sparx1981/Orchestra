// Product spec export to Word (.docx), RTF, and PDF. All three formats share one
// lightweight Markdown parser (parseMarkdownLiteBlocks) and one brand style (BRAND below)
// so headings/bullets/tables/the title page render consistently across formats instead of
// three independently-drifting implementations.
//
// The visual style here (colors, type sizes, header/footer layout, title page structure)
// was reverse-engineered from a reference document the user provided (a Trimble/SketchUp
// product spec) — see BRAND for the exact palette and the title-page/header/footer builders
// below for the layout. Business-specific wording in that reference ("CONFIDENTIAL — FOR
// INTERNAL USE", a real company name, a fixed "v1.0") was deliberately NOT copied verbatim —
// this tool generates drafts for arbitrary projects, so those became generic equivalents
// ("AI-GENERATED — DRAFT", "Generated by Orchestra") rather than false claims.
//
// KNOWN LIMITATION: this is a "lite" Markdown parser, not a full CommonMark implementation.
// It handles what the drafting agents actually produce (headings, bullets, numbered lists,
// fenced code blocks, pipe tables, **bold** spans, plain paragraphs) but does NOT handle
// nested/multi-level lists (everything renders at a single indent level) or table cell
// alignment markers (:---:) beyond stripping them.

