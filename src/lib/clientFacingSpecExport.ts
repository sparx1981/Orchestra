// Client-Facing Product Spec export to Word (.docx), RTF, and PDF — the non-technical
// companion document (see ClientFacingSpec in productSpecTypes.ts and
// handleGenerateClientSpec in ProductTab.tsx). Reuses the same brand palette and Markdown
// block parser as the technical spec's own exporters (productSpecExport.ts) so the two
// documents look like a matched pair, but with a simpler title page (no grounded-sources
// list or per-section "Drafted by" bylines — a stakeholder reading this doesn't need to
// know which AI agent wrote which paragraph) and no target-tool/tech metadata, since this
// document is deliberately scoped to what the product does and looks like, not how it's built.

import { PDFDocument, StandardFonts, rgb, type PDFPage, type PDFFont } from "pdf-lib";
import type { Paragraph as ParagraphT, Table as TableT } from "docx";
import type { ProductSpec } from "./productSpecTypes";
import {
  BRAND,
  hexToRgb01,
  parseMarkdownLiteBlocks,
  splitBoldSegments,
  stripBoldMarkers,
  escapeRtf,
  buildRtfTable,
  wrapText,
  RTF_COLOR_TABLE,
  RTF_CF,
} from "./productSpecExport";

function clientSpecDateLabel(spec: ProductSpec): string {
  const at = spec.clientFacingSpec?.generatedAt || spec.createdAt;
  return new Date(at).toLocaleDateString(undefined, { year: "numeric", month: "long" });
}

// A style-inspiration reference (if the product owner attached one during the technical
// spec's pre-flight — see ProductSpecPreflightQuestion.isStyleInspiration) is genuinely
// client-relevant ("here's the look we designed toward"), unlike the rest of pre-flight
// Q&A, which is either implementation detail or already folded into the sections below.
function styleInspirationLine(spec: ProductSpec): string | null {
  const qa = (spec.preflightQuestions || []).find(q => q.isStyleInspiration && q.answer);
  return qa?.answer && !/^no style inspiration/i.test(qa.answer) ? qa.answer : null;
}

// ---------------------------------------------------------------------------
// DOCX
// ---------------------------------------------------------------------------

export async function buildClientFacingSpecDocx(spec: ProductSpec): Promise<Blob> {
  const {
    Document, Packer, Paragraph, TextRun, HeadingLevel, Header, Footer, PageNumber, PageBreak,
    Table, TableRow, TableCell, WidthType, ShadingType, BorderStyle,
  } = await import("docx");

  const PAGE_W = 12240;
  const PAGE_H = 15840;
  const MARGIN = 1080;
  const CONTENT_W = PAGE_W - MARGIN * 2;

  const dateLabel = clientSpecDateLabel(spec);
  const styleLine = styleInspirationLine(spec);
  const noBorder = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };

  const header = new Header({
    children: [
      new Table({
        width: { size: CONTENT_W, type: WidthType.DXA },
        columnWidths: [CONTENT_W / 2, CONTENT_W / 2],
        borders: { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder, insideHorizontal: noBorder, insideVertical: noBorder },
        rows: [
          new TableRow({
            children: [
              new TableCell({
                width: { size: CONTENT_W / 2, type: WidthType.DXA },
                borders: { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder },
                children: [new Paragraph({ children: [new TextRun({ text: `${spec.title} — Client-Facing Product Spec`, font: "Arial", bold: true, color: BRAND.blue, size: 18 })] })],
              }),
              new TableCell({
                width: { size: CONTENT_W / 2, type: WidthType.DXA },
                borders: { top: noBorder, bottom: noBorder, left: noBorder, right: noBorder },
                children: [new Paragraph({ alignment: "right", children: [new TextRun({ text: "DRAFT — FOR CLIENT REVIEW", font: "Arial", color: BRAND.muted, size: 16 })] })],
              }),
            ],
          }),
        ],
      }),
      new Paragraph({ border: { bottom: { style: BorderStyle.SINGLE, color: BRAND.blue, size: 6, space: 1 } }, spacing: { after: 80, before: 0 } }),
    ],
  });

  const footer = new Footer({
    children: [
      new Paragraph({
        border: { top: { style: BorderStyle.SINGLE, color: BRAND.ruleLight, size: 4, space: 1 } },
        tabStops: [{ type: "right", position: CONTENT_W - 60 }],
        spacing: { before: 80, after: 0 },
        children: [
          new TextRun({ text: `Generated by Orchestra — ${dateLabel}`, font: "Arial", color: BRAND.muted, size: 16 }),
          new TextRun({ text: "\tPage ", font: "Arial", color: BRAND.muted, size: 16 }),
          new TextRun({ children: [PageNumber.CURRENT], font: "Arial", color: BRAND.muted, size: 16 }),
        ],
      }),
    ],
  });

  const children: (ParagraphT | TableT)[] = [];

  // --- Title page ---------------------------------------------------------
  children.push(
    new Paragraph({ spacing: { before: 1440, after: 0 }, children: [new TextRun({ text: "CLIENT-FACING PRODUCT SPECIFICATION", font: "Arial", bold: true, color: BRAND.blue, size: 20, characterSpacing: 120 })] }),
    new Paragraph({ spacing: { before: 60, after: 80 }, children: [new TextRun({ text: spec.title, font: "Arial", bold: true, color: BRAND.navy, size: 72 })] })
  );
  if (spec.subtitle) {
    children.push(new Paragraph({ spacing: { before: 0, after: 60 }, children: [new TextRun({ text: spec.subtitle, font: "Arial", color: BRAND.blue, size: 36 })] }));
  }
  children.push(
    new Paragraph({ border: { bottom: { style: BorderStyle.SINGLE, color: BRAND.accent, size: 16, space: 1 } }, spacing: { before: 200, after: 0 } }),
    new Paragraph({ spacing: { before: 400, after: 80 }, children: [new TextRun({ text: "Document Purpose", font: "Arial", bold: true, color: BRAND.navy, size: 24 })] }),
    new Paragraph({
      spacing: { before: 60, after: 100 },
      children: [new TextRun({ text: `This document describes what ${spec.title} will do, why it's being built, and how it behaves and looks from a user's point of view — for stakeholder review, not for engineering handoff. ${spec.appConcept || ""}`, font: "Arial", color: BRAND.gray, size: 22 })],
    })
  );
  if (styleLine) {
    children.push(
      new Paragraph({ spacing: { before: 240, after: 60 }, children: [new TextRun({ text: "Style Inspiration", font: "Arial", bold: true, color: BRAND.navy, size: 20 })] }),
      new Paragraph({ spacing: { after: 100 }, children: [new TextRun({ text: styleLine, font: "Arial", color: BRAND.gray, size: 18 })] })
    );
  }
  children.push(
    new Paragraph({
      spacing: { before: 480, after: 80 },
      children: [
        new TextRun({ text: "Prepared:  ", font: "Arial", bold: true, color: BRAND.gray, size: 20 }),
        new TextRun({ text: dateLabel, font: "Arial", color: BRAND.gray, size: 20 }),
      ],
    }),
    new Paragraph({ children: [new PageBreak()] })
  );

  // --- Section content -----------------------------------------------------
  const buildTable = (rows: string[][]) => {
    const [headerRow, ...bodyRows] = rows;
    const colCount = headerRow.length;
    const baseWidth = Math.floor(CONTENT_W / colCount);
    const colWidths = Array(colCount).fill(baseWidth);
    colWidths[colCount - 1] += CONTENT_W - baseWidth * colCount;

    const cellBorder = { style: BorderStyle.SINGLE, size: 1, color: BRAND.tableBorder };
    const cellBorders = { top: cellBorder, bottom: cellBorder, left: cellBorder, right: cellBorder };
    const cellMargins = { top: 100, bottom: 100, left: 120, right: 120 };

    const makeCell = (text: string, width: number, opts: { header?: boolean; firstCol?: boolean }) =>
      new TableCell({
        width: { size: width, type: WidthType.DXA },
        borders: cellBorders,
        margins: cellMargins,
        shading: opts.header
          ? { fill: BRAND.navy, type: ShadingType.CLEAR, color: "auto" }
          : opts.firstCol
          ? { fill: BRAND.labelFill, type: ShadingType.CLEAR, color: "auto" }
          : undefined,
        children: [new Paragraph({ children: [new TextRun({ text: stripBoldMarkers(text), font: "Arial", bold: !!(opts.header || opts.firstCol), color: opts.header ? "FFFFFF" : opts.firstCol ? BRAND.navy : BRAND.gray, size: 20 })] })],
      });

    return new Table({
      width: { size: CONTENT_W, type: WidthType.DXA },
      columnWidths: colWidths,
      rows: [
        new TableRow({ tableHeader: true, children: headerRow.map((cell, ci) => makeCell(cell, colWidths[ci], { header: true })) }),
        ...bodyRows.map(r => new TableRow({ children: r.map((cell, ci) => makeCell(cell, colWidths[ci], { firstCol: ci === 0 })) })),
      ],
    });
  };

  for (const section of spec.clientFacingSpec?.sections || []) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 360, after: 200 }, children: [new TextRun({ text: section.heading, font: "Arial", bold: true, color: BRAND.navy, size: 36 })] }));
    children.push(new Paragraph({ border: { bottom: { style: BorderStyle.SINGLE, color: BRAND.blue, size: 12, space: 1 } }, spacing: { after: 200, before: 0 } }));

    for (const block of parseMarkdownLiteBlocks(section.content)) {
      if (block.type === "h2") {
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 300, after: 80 }, children: [new TextRun({ text: block.text, font: "Arial", bold: true, color: BRAND.blue, size: 28 })] }));
      } else if (block.type === "h3") {
        children.push(new Paragraph({ heading: HeadingLevel.HEADING_3, spacing: { before: 200, after: 60 }, children: [new TextRun({ text: block.text, font: "Arial", bold: true, color: BRAND.gray, size: 24 })] }));
      } else if (block.type === "code") {
        for (const codeLine of block.text.split("\n")) {
          children.push(new Paragraph({ children: [new TextRun({ text: codeLine || " ", font: "Consolas", size: 18, color: BRAND.gray })], spacing: { after: 0 } }));
        }
      } else if (block.type === "table") {
        children.push(buildTable(block.rows));
        children.push(new Paragraph({ spacing: { after: 200 } }));
      } else if (block.type === "bullet" || block.type === "numbered") {
        children.push(
          new Paragraph({
            children: splitBoldSegments(block.text).map(seg => new TextRun({ text: seg.text, bold: seg.bold, font: "Arial", size: 22, color: seg.bold ? BRAND.navy : BRAND.gray })),
            bullet: { level: 0 },
            spacing: { after: 40, before: 40 },
          })
        );
      } else {
        children.push(
          new Paragraph({
            children: splitBoldSegments(block.text).map(seg => new TextRun({ text: seg.text, bold: seg.bold, font: "Arial", size: 22, color: seg.bold ? BRAND.navy : BRAND.gray })),
            spacing: { after: 100, before: 60 },
          })
        );
      }
    }
  }

  children.push(
    new Paragraph({ border: { bottom: { style: BorderStyle.SINGLE, color: BRAND.ruleLight, size: 4, space: 1 } }, spacing: { before: 160, after: 160 } }),
    new Paragraph({ alignment: "center", spacing: { before: 240, after: 80 }, children: [new TextRun({ text: "— End of Document —", font: "Arial", italics: true, color: BRAND.muted, size: 20 })] }),
    new Paragraph({ alignment: "center", children: [new TextRun({ text: `${spec.title} Client-Facing Product Spec  |  ${dateLabel}  |  AI-Generated Draft`, font: "Arial", color: BRAND.faint, size: 18 })] })
  );

  const doc = new Document({
    sections: [
      {
        properties: { page: { size: { width: PAGE_W, height: PAGE_H }, margin: { top: MARGIN, right: MARGIN, bottom: MARGIN, left: MARGIN, header: 708, footer: 708 } } },
        headers: { default: header },
        footers: { default: footer },
        children,
      },
    ],
  });
  return Packer.toBlob(doc);
}

