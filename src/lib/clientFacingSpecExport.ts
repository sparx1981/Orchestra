export function buildClientFacingSpecRtf(spec: ProductSpec): string {
  const dateLabel = clientSpecDateLabel(spec);
  const styleLine = styleInspirationLine(spec);
  const lines: string[] = [];

  lines.push(
    `{\\rtf1\\ansi\\deff0{\\fonttbl{\\f0 Arial;}{\\f1 Consolas;}}{\\colortbl;${RTF_COLOR_TABLE.map(cHex => `\\red${parseInt(cHex.slice(0, 2), 16)}\\green${parseInt(cHex.slice(2, 4), 16)}\\blue${parseInt(cHex.slice(4, 6), 16)};`).join("")}}`
  );
  lines.push(
    `{\\header\\pard\\tqr\\tx9360\\fs18\\b\\cf${RTF_CF.blue} ${escapeRtf(`${spec.title} — Client-Facing Product Spec`)}\\b0\\tab\\fs16\\cf${RTF_CF.muted} ${escapeRtf("DRAFT — FOR CLIENT REVIEW")}\\par}`,
    `{\\footer\\pard\\tqr\\tx9360\\fs16\\cf${RTF_CF.muted} ${escapeRtf(`Generated by Orchestra — ${dateLabel}`)}\\tab Page \\chpgn\\par}`
  );

  lines.push(`\\f0\\fs20\\b\\cf${RTF_CF.blue}\\expndtw60 CLIENT-FACING PRODUCT SPECIFICATION\\expndtw0\\b0\\par`);
  lines.push(`\\fs72\\b\\cf${RTF_CF.navy} ${escapeRtf(spec.title)}\\b0\\par`);
  if (spec.subtitle) lines.push(`\\fs36\\cf${RTF_CF.blue} ${escapeRtf(spec.subtitle)}\\par`);
  lines.push(`\\brdrb\\brdrs\\brdrw20\\brdrcf${RTF_CF.accent}\\par\\pard\\par`);
  lines.push(`\\fs24\\b\\cf${RTF_CF.navy} Document Purpose\\b0\\par`);
  lines.push(
    `\\fs22\\cf${RTF_CF.gray} This document describes what ${escapeRtf(spec.title)} will do, why it's being built, and how it behaves and looks from a user's point of view — for stakeholder review, not for engineering handoff. ${escapeRtf(spec.appConcept || "")}\\par\\par`
  );
  if (styleLine) {
    lines.push(`\\fs20\\b\\cf${RTF_CF.navy} Style Inspiration\\b0\\par`);
    lines.push(`\\fs18\\cf${RTF_CF.gray} ${escapeRtf(styleLine)}\\par\\par`);
  }
  lines.push(`\\fs20\\cf${RTF_CF.gray}\\b Prepared:\\b0  ${escapeRtf(dateLabel)}\\par`);
  lines.push("\\page");

  for (const section of spec.clientFacingSpec?.sections || []) {
    lines.push(`\\fs36\\b\\cf${RTF_CF.navy} ${escapeRtf(section.heading)}\\b0\\par`);
    lines.push(`\\brdrb\\brdrs\\brdrw15\\brdrcf${RTF_CF.blue}\\par\\pard\\par`);

    for (const block of parseMarkdownLiteBlocks(section.content)) {
      if (block.type === "table") {
        lines.push(buildRtfTable(block.rows));
        continue;
      }
      const plain = escapeRtf(stripBoldMarkers(block.text));
      if (block.type === "h2") {
        lines.push(`\\fs28\\b\\cf${RTF_CF.blue} ${plain}\\b0\\par`);
      } else if (block.type === "h3") {
        lines.push(`\\fs24\\b\\cf${RTF_CF.gray} ${plain}\\b0\\par`);
      } else if (block.type === "code") {
        for (const codeLine of block.text.split("\n")) lines.push(`\\f1\\fs18\\cf${RTF_CF.gray} ${escapeRtf(codeLine || " ")}\\f0\\par`);
      } else if (block.type === "bullet" || block.type === "numbered") {
        lines.push(`\\fs22\\cf${RTF_CF.gray} \\bullet \\tab ${plain}\\par`);
      } else {
        lines.push(`\\fs22\\cf${RTF_CF.gray} ${plain}\\par`);
      }
    }
    lines.push("\\par");
  }

  lines.push(`\\brdrb\\brdrs\\brdrw10\\brdrcf${RTF_CF.ruleLight}\\par\\pard\\par`);
  lines.push(`\\qc\\fs20\\i\\cf${RTF_CF.muted} ${escapeRtf("— End of Document —")}\\i0\\par`);
  lines.push(`\\qc\\fs18\\cf${RTF_CF.faint} ${escapeRtf(spec.title)} Client-Facing Product Spec  |  ${escapeRtf(dateLabel)}  |  AI-Generated Draft\\par`);
  lines.push("}");
  return lines.join("\n");
}

